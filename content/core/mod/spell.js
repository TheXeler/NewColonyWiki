"    <h2>施法与结算</h2>",
"    <p>施法只支持地面位置，不支持指向实体，也不会自动征召。吟诵总时长为所有符文时长之和，按模拟 tick 计时。注册命令可以识别单个、嵌套与批量的接收者；原生移动、停止、防御、攻击、征召、阵型、解除征召、指定新工作与职业变更都会打断吟诵，实际血量伤害与 tick 血量变化同样打断，护盾吸收不打断。查看界面与法术查询不算游戏指令。</p>",
"    <p>吟诵结束会重新校验装备与精力，准备 UUID、运行状态与引用后由原生分配实体、扣除精力并提交状态。执行失败时只移除本次未完成的法术实体并记录错误，已扣除的精力不恢复。</p>",
"    <p>飞行使用扫掠碰撞，查询实体碰撞体与途经的非空气方块，取最早命中；默认发射位置取施法者碰撞体中心。命中时按剩余魔力结算固定伤害、斥力、范围与后效时长，正持续时间每 10 tick 重新查询范围并结算一次，到期删除。没有敌我筛选；零范围表示点与碰撞体的相交；同小队成员的重复兵模不会重复扣同一血池。</p>",
